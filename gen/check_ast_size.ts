import type {RustASTTypeName} from "./ir.ts";
import {astName} from "./ir.ts";

export function generateASTSizeCheckerRustTest(astTypes: RustASTTypeName[]): string {
    let ret = "";
    ret += `// ==========================================\n`;
    ret += `//  Generated by Script (see /script/index.ts)\n`;
    ret += `//  DO NOT EDIT THIS FILE DIRECTLY\n`;
    ret += `//  In "/src/parser/tests/ast_size_checker.rs"\n`;
    ret += `// ==========================================\n\n`;
    // TIBINEKO-FORK: module path of the generated AST in the consumer crate.
    ret += `use crate::parser::generated_ast::*;\n\n`;
    ret += `#[test]\n`;
    ret += `#[ignore]\n`;
    ret += `fn report_ast_size() {\n`;
    ret += `    println!("===BEGIN_REPORT===");\n`
    for (const ast of astTypes) {
        ret += `    println!("${ast}:{}", size_of::<${ast}>());\n`
    }
    ret += `    println!("===END_REPORT===");\n`
    ret += `}\n`;
    return ret;
}

export function parseASTSizeCheckerResult(result: string): { ast: RustASTTypeName, size: number }[] {
    const beginMarker = "===BEGIN_REPORT===";
    const endMarker = "===END_REPORT===";
    const begin = result.indexOf(beginMarker);
    const end = result.indexOf(endMarker);
    if (begin === -1 || end === -1 || end <= begin) {
        return [];
    }
    const report = result.substring(begin + beginMarker.length, end);
    return report.split("\n").map(line => line.trim()).filter(line => line.length > 0).map(line => {
        const sep = line.lastIndexOf(":");
        const ast = astName(line.slice(0, sep));
        const size = parseInt(line.slice(sep + 1), 10);
        return { ast, size };
    }).filter(({ size }) => Number.isFinite(size));
}
