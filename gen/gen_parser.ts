import type {IR, BranchParserFunction, ProductParserFunction, HookParserFunction} from "./ir.ts";

/**
 * A concrete Rust value for a `$payload$` in a token expression, so the
 * token can appear in the `&[Token]` expected list. A `_` placeholder is
 * not a valid Rust value expression, which is why `$` tokens used to be
 * dropped from the list entirely (and `parse_Value` reported only
 * `[LeftBracket, LeftParen]`). Returns null for payload types no value can
 * be fabricated for; those tokens stay out of the list.
 *
 * Two constraints shape what can be fabricated:
 * - The list is `&'static [Token]` and lives in a function-local `const`
 *   item (see `generateBranchParseFunction`), where `Span::new(0, 0)` is
 *   evaluated at compile time — so the consumer's `Span::new` must be a
 *   `const fn` (the example's is). An inline array would not work even
 *   then: rvalue promotion does not apply to const fn calls.
 * - `Token::Identifier` is never fabricated: its payload is a `Symbol`,
 *   which has no public const constructor. The `$...$` in the tokenmap
 *   names the AST-side payload, not the token's. Identifier-ness is
 *   conveyed instead by the `identifier` flag passed to
 *   `IParseErr::build`, which diagnostics render as "expected an
 *   identifier".
 * - Float literals are never fabricated either: the token's payload is
 *   a wrapper type (e.g. `HashableFloat<f32>`), not a plain `f32`, and
 *   the generator cannot know its constructor.
 */
export function expectedTokenValue(token: string): string | null {
    // Token::Identifier's payload is a Symbol: no const value exists.
    if (/^Token::Identifier\(/.test(token)) return null;
    let unknown = false;
    const replaced = token.replace(/\$([^$]+)\$/g, (_m, payload: string) => {
        switch (payload) {
            case "i8": case "i16": case "i32": case "i64":
            case "u8": case "u16": case "u32": case "u64":
            case "isize": case "usize":
                return "0";
            case "bool":
                return "false";
            case "char":
                return "'\\0'";
            case "Span":
                return "Span::new(0, 0)";
            default:
                unknown = true;
                return _m;
        }
    });
    return unknown ? null : replaced;
}

export class ParserGenerator {
    public generateParser(ir: IR): string {
        const funcs = [];
        for (const func of ir) {
            switch (func.kind) {
                case "branch":
                    funcs.push(this.generateBranchParseFunction(func));
                    break;
                case "product":
                    funcs.push(this.generateProductParserFunction(func));
                    break;
                case "hook":
                    funcs.push(this.generateHookParserFunction(func));
                    break;
            }
        }
        let ret = "";
        ret += `// ==========================================\n`;
        ret += `//  Generated by Script (see /script/index.ts)\n`;
        ret += `//  DO NOT EDIT THIS FILE DIRECTLY\n`;
        ret += `//  In "/src/parser/generated_parser.rs"\n`;
        ret += `// ==========================================\n\n`;
        ret += `#![allow(unused_variables)]\n`;
        ret += `#![allow(clippy::match_single_binding)]\n`;
        // Not every grammar uses every token category or the tracer guard.
        ret += `#![allow(unused_imports)]\n\n`
        // TIBINEKO-FORK: module paths of the consumer crate. Edit if your runtime lives elsewhere.
        ret += `use crate::parser::base_parser::BaseParser;\n`;
        ret += `use crate::parser::errors::IParseErr;\n`;
        ret += `use crate::parser::tracer::TraceGuard;\n`;
        ret += `use crate::parser::ast_node::ASTNode;\n`;
        // Needed for the `Span::new(0, 0)` placeholders in error `expected`
        // lists (see expectedTokenValue above).
        ret += `use crate::compiler::span::Span;\n`;
        ret += `use crate::tokenizer::tokens::{Delimiter, Keyword, Literal, Operator, Comment, Token};\n\n`;
        ret += `#[allow(clippy::wildcard_imports)]\n`;
        ret += `use crate::parser::generated_ast::*;\n\n`;
        ret += `#[allow(non_snake_case)]\n`;
        ret += `pub trait GeneratedParser: BaseParser + Sized {\n`;
        ret += `    type TraceGuard;\n`;
        ret += `    fn trace(name: &'static str) -> Self::TraceGuard;\n`;
        ret += funcs.join("\n");
        ret += `}\n`;
        return ret;
    }

    private generateBranchParseFunction(func: BranchParserFunction): string {
        let ret = "";
        ret += `\n    fn parse_${func.functionName}(&mut self) -> Result<${func.astTypeName}, Self::Error> {\n`;

        const unmatchedFallback = func.unmatchedFallback;
        // `$...$` payloads are replaced with concrete defaults (see
        // expectedTokenValue) instead of being dropped, so the error lists
        // every token that could have appeared here.
        const expected = [...new Set(func.expectedTerminals
            .map(expectedTokenValue)
            .filter((t): t is string => t !== null && t !== "_"))];
        // The list is `&'static [Token]`, so it lives in a function-local
        // `const` item rather than an inline array: rvalue promotion does
        // not apply to const fn calls, so an inline `Span::new(0, 0)`
        // would make the whole array a temporary and fail to compile
        // (E0716). In a `const` item the call is evaluated at compile
        // time, which is also why the consumer's `Span::new` must be a
        // `const fn`. An empty list stays an inline `&[]`.
        const expectedName = `EXPECTED_${func.functionName.toUpperCase()}`;
        const expectedExpr = expected.length === 0 ? "&[]" : expectedName;
        const expectedConst = expected.length === 0 ? ""
            : `        const ${expectedName}: &[Token] = &[${expected.join(", ")}];\n`;
        // The first argument to `IParseErr::build` is whether an identifier
        // was expected — not, as before, whether any `$` token was present
        // (that made `parse_Value` claim an identifier was expected).
        const expectsIdentifier = func.expectedTerminals.some(t => t.includes("Identifier"));
        const errorResult = `Err(Self::Error::build(\n`
            + `                ${expectsIdentifier},\n`
            + `                ${expectedExpr},\n`
            + `                self.enviroment(),\n`
            + `            ))`;
        const fallbackResult = () => {
            if (!unmatchedFallback) return errorResult;
            const parseCall = unmatchedFallback.isBoxed
                ? `self.alloc_box(|this| this.parse_${unmatchedFallback.astTypeName}())?`
                : `self.parse_${unmatchedFallback.astTypeName}()?`;
            return `Ok(${func.astTypeName}::${unmatchedFallback.astTypeName}(${parseCall}))`;
        };
        const parseCandidate = (astType: string, isBoxed: boolean) => {
            if (!unmatchedFallback) {
                const parseCall = isBoxed
                    ? `self.alloc_box(|this| this.parse_${astType}())?`
                    : `self.parse_${astType}()?`;
                return `Ok(${func.astTypeName}::${astType}(${parseCall}))`;
            }
            const wrappedNode = isBoxed ? `self.alloc(node)` : `node`;
            return `match self.backtrack_clean(|this| this.parse_${astType}()) {\n`
                + `                    Ok(node) => Ok(${func.astTypeName}::${astType}(${wrappedNode})),\n`
                + `                    Err(_) => ${fallbackResult()},\n`
                + `                }`;
        };

        if (func.branchesJudgebleInPeek0.length === 0 &&
            func.branchesJudgebleInPeek1.length === 0 &&
            (func.branchesFallbackInPeek1 || []).length === 0 &&
            func.branchesNeedBacktrack.length === 0 &&
            !unmatchedFallback) {
            ret += `        Err(Self::Error::build(false, &[], self.enviroment()))\n`;
            ret += `    }\n`;
            return ret;
        }

        ret += expectedConst;
        ret += `        match self.peek::<0>() {\n`;

        const peek0Groups = new Map<string, { isBoxed: boolean, terminals: Set<string> }>();
        for (const branch of func.branchesJudgebleInPeek0) {
            if (unmatchedFallback && branch.astTypeName === unmatchedFallback.astTypeName) continue;
            if (!peek0Groups.has(branch.astTypeName)) {
                peek0Groups.set(branch.astTypeName, { isBoxed: branch.isBoxed, terminals: new Set() });
            }
            peek0Groups.get(branch.astTypeName)!.terminals.add(branch.firstTerminal.replace(/\$.*\$/, "_"));
        }
        const sortedKeys = Array.from(peek0Groups.keys()).sort();
        for (const astType of sortedKeys) {
            const group = peek0Groups.get(astType)!;
            const pattern = Array.from(group.terminals).sort().join(" | ");
            ret += `            Some(${pattern}) => ${parseCandidate(astType, group.isBoxed)},\n`;
        }

        const complexFirstTerminals = [...new Set([
            ...func.branchesJudgebleInPeek1.map(b => b.firstTerminal),
            ...func.branchesNeedBacktrack.map(b => b.firstTerminal),
            ...(func.branchesFallbackInPeek1 || []).map(b => b.firstTerminal),
        ])].filter(t0 => !(unmatchedFallback && t0 === "Token::Invalid"));

        for (const t0 of complexFirstTerminals.sort()) {
            const cleanT0 = t0.replace(/\$.*\$/, "_");
            ret += `            Some(${cleanT0}) => match self.peek::<1>() {\n`;

            const peek1 = func.branchesJudgebleInPeek1.filter(b =>
                b.firstTerminal === t0 && !(unmatchedFallback && b.astTypeName === unmatchedFallback.astTypeName),
            );
            const peek1Groups = new Map<string, { isBoxed: boolean, terminals: Set<string> }>();
            for (const branch of peek1) {
                if (!peek1Groups.has(branch.astTypeName)) {
                    peek1Groups.set(branch.astTypeName, { isBoxed: branch.isBoxed, terminals: new Set() });
                }
                peek1Groups.get(branch.astTypeName)!.terminals.add(branch.secondTerminal.replace(/\$.*\$/, "_"));
            }

            for (const [astType, group] of peek1Groups.entries()) {
                const pattern = Array.from(group.terminals).join(" | ");
                ret += `                Some(${pattern}) => ${parseCandidate(astType, group.isBoxed)},\n`;
            }

            const backtrack = [...new Map(
                func.branchesNeedBacktrack
                    .filter(b => b.firstTerminal === t0 && !(unmatchedFallback && b.astTypeName === unmatchedFallback.astTypeName))
                    .map(branch => [`${branch.astTypeName}:${branch.isBoxed}`, branch]),
            ).values()];
            const localFallback = (func.branchesFallbackInPeek1 || []).find(b =>
                b.firstTerminal === t0 && !(unmatchedFallback && b.astTypeName === unmatchedFallback.astTypeName),
            );
            if (backtrack.length > 0) {
                ret += `                _ => {\n`;
                for (const branch of backtrack) {
                    const wrappedNode = branch.isBoxed ? `self.alloc(node)` : `node`;
                    const tryCall = unmatchedFallback ? "backtrack_clean" : "backtrack";
                    ret += `                    if let Ok(node) = self.${tryCall}(|this| this.parse_${branch.astTypeName}()) {\n`;
                    ret += `                        return Ok(${func.astTypeName}::${branch.astTypeName}(${wrappedNode}));\n`;
                    ret += `                    }\n`;
                }
                if (localFallback) {
                    if (unmatchedFallback) {
                        const wrappedNode = localFallback.isBoxed ? `self.alloc(node)` : `node`;
                        ret += `                    if let Ok(node) = self.backtrack_clean(|this| this.parse_${localFallback.astTypeName}()) {\n`;
                        ret += `                        return Ok(${func.astTypeName}::${localFallback.astTypeName}(${wrappedNode}));\n`;
                        ret += `                    }\n`;
                        ret += `                    ${fallbackResult()}\n`;
                    } else {
                        const parseCall = localFallback.isBoxed
                            ? `self.alloc_box(|this| this.parse_${localFallback.astTypeName}())?`
                            : `self.parse_${localFallback.astTypeName}()?`;
                        ret += `                    Ok(${func.astTypeName}::${localFallback.astTypeName}(${parseCall}))\n`;
                    }
                } else {
                    ret += `                    ${fallbackResult()}\n`;
                }
                ret += `                }\n`;
            } else if (localFallback) {
                ret += `                _ => ${parseCandidate(localFallback.astTypeName, localFallback.isBoxed)},\n`;
            } else {
                ret += `                _ => ${fallbackResult()},\n`;
            }
            ret += `            },\n`;
        }

        ret += `            _ => ${fallbackResult()},\n`;
        ret += `        }\n`;
        ret += `    }\n`;

        return ret;
    }

    private generateProductParserFunction(func: ProductParserFunction): string {
        let ret = "";
        let isManual = func.elements.some(element => element.kind === "terminal"
        // TIBINEKO-FORK: products containing a `$`/Invalid terminal become hand-written (`manual_parser`).
            && (element.tokenTypeName.includes("$") || element.tokenTypeName === "Token::Invalid"));
        if (isManual) {
            ret += `\n    fn parse_${func.functionName}(&mut self) -> Result<${func.astTypeName}, Self::Error>;\n`;
            return ret;
        }
        ret += `\n    fn parse_${func.functionName}(&mut self) -> Result<${func.astTypeName}, Self::Error> {\n`;
        ret += `        let _guard = Self::trace(${func.astTypeName}::ast_name());\n`
        for (const element of func.elements) {
            switch (element.kind) {
                case "normal":
                    ret += `        let v_${element.name} = self.parse_${element.astTypeName}()?;\n`;
                    break;
                case "boxed":
                    ret += `        let v_${element.name} = self.alloc_box(|this| this.parse_${element.astTypeName}())?;\n`;
                    break;
                case "option":
                    ret += `        let v_${element.name} = self.optional(|this| this.parse_${element.astTypeName}());\n`;
                    break;
                case "repeat":
                    ret += `        let v_${element.name} = self.repeat(Self::parse_${element.astTypeName})?;\n`;
                    break;
                case "optionWithBox":
                    ret += `        let v_${element.name} = self.optional_box(|this| this.parse_${element.astTypeName}());\n`;
                    break;
                case "terminal":
                    if (!element.tokenTypeName.includes("$")) {
                        ret += `        self.expect(&${element.tokenTypeName})?;\n`;
                    }
                    break;
            }
        }
        ret += `        Ok(${func.astTypeName} {\n`;
        const sortedElements = [...func.elements].sort((a, b) => {
            const nameA = a.kind === 'terminal' ? a.tokenTypeName : a.astTypeName;
            const nameB = b.kind === 'terminal' ? b.tokenTypeName : b.astTypeName;
            return nameA.localeCompare(nameB);
        });
        for (const element of sortedElements) {
            if (element.kind !== "terminal") {
                ret += `            ${element.name}: v_${element.name},\n`;
            }
        }
        ret += `        })\n`;
        ret += `    }\n`;
        return ret;
    }

    private generateHookParserFunction(func: HookParserFunction): string {
        return `\n    fn parse_${func.functionName}(&mut self) -> Result<${func.astTypeName}, Self::Error>;\n`;
    }

}

